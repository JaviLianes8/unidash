"""Exact-form contracts against every normalization or coercion of the form argument.

The cases are generated by hand-written rules, not taken from an external source. A form is
accepted only when it is a str whose characters are exactly one of the three names, so no
stripping, case folding, fuzzy matching, transliteration or buffer decoding may get through.
"""

from __future__ import annotations

import array
import enum
import itertools
import string
import sys
import unicodedata
from collections import UserString
from collections.abc import Callable
from pathlib import PurePosixPath
from typing import Any

import pytest

from unidash import dash_table, find_dashes, fold_dashes, iter_fold_dashes
from unidash._cli import main

FORMS = ("ascii", "tex", "typographic")
APIS = [fold_dashes, iter_fold_dashes, find_dashes, dash_table]
VALUE_ERROR = r"^form must be one of ascii, tex, typographic$"
TYPE_ERROR = r"^form must be a str$"
SPACES = "".join(c for c in map(chr, range(sys.maxunicode + 1)) if c.isspace())
# Characters a normalization could drop: separators, controls, format and combining marks.
DROPPABLE = "".join(
    c
    for c in map(chr, range(sys.maxunicode + 1))
    if c.isspace() or unicodedata.category(c) in {"Cc", "Cf", "Mn", "Me", "Zs", "Zl", "Zp"}
)
PADS = [*DROPPABLE, *string.punctuation, "\r\n", "\n\r", "  ", "\t\n"]
LOOKALIKES = {"a": "\u0430\u03b1", "c": "\u0441\u03f2", "e": "\u0435", "i": "\u0456\u0131"}
LOOKALIKES |= {"o": "\u043e\u03bf", "p": "\u0440\u03c1", "x": "\u0445\u03c7", "y": "\u0443"}
LOOKALIKES |= {"s": "\u0455\u017f", "t": "\u0442"}


def _padded(form: str) -> list[str]:
    cases = []
    for pad in PADS:
        cases += [pad + form, form + pad, pad + form + pad, form[:1] + pad + form[1:]]
    return cases


def _near_misses(form: str) -> list[str]:
    cases = {form + form, form.upper(), form.title(), form.capitalize(), form.swapcase()}
    for flags in itertools.product((False, True), repeat=len(form)):
        cases.add("".join(c.upper() if up else c for c, up in zip(form, flags, strict=True)))
    for start, stop in itertools.combinations(range(len(form) + 1), 2):
        cases.add(form[start:stop])
    for index in range(len(form)):
        cases.add(form[:index] + form[index + 1 :])
        cases.add(form[:index] + form[index + 1 : index + 2] + form[index] + form[index + 2 :])
        for letter in string.ascii_lowercase + string.digits:
            cases.add(form[:index] + letter + form[index + 1 :])
        for lookalike in LOOKALIKES.get(form[index], ""):
            cases.add(form[:index] + lookalike + form[index + 1 :])
    for extra in string.ascii_letters + string.digits:
        cases |= {form + extra, extra + form}
    cases.add("".join(LOOKALIKES.get(c, c)[0] for c in form))
    return sorted(cases - set(FORMS))


ALIASES = ["latex", "plain", "unicode", "default", "none", "0", "1", "2", "-", "--", "a", "t"]
STR_CASES = sorted({*ALIASES, *(case for f in FORMS for case in _padded(f) + _near_misses(f))})


class Named(enum.Enum):
    ASCII = "ascii"
    TEX = "tex"
    TYPOGRAPHIC = "typographic"


class Spelled:
    def __init__(self, form: str) -> None:
        self.form = form

    def __str__(self) -> str:
        return self.form

    def __fspath__(self) -> str:
        return self.form

    def __eq__(self, other: object) -> bool:
        return other == self.form

    def __hash__(self) -> int:
        return hash(self.form)


def _objects(form: str) -> list[object]:
    raw = form.encode("ascii")
    return [
        memoryview(raw),
        memoryview(bytearray(raw)),
        memoryview(array.array("B", raw)),
        memoryview(raw).cast("c"),
        array.array("B", raw),
        array.array("b", raw),
        form.encode("utf-16"),
        form.encode("utf-32"),
        UserString(form),
        PurePosixPath(form),
        Spelled(form),
        Named(form),
        list(form),
        tuple(form),
        [form],
        (form,),
        {form},
        frozenset({form}),
        {form: form},
        iter(form),
    ]


OBJECT_CASES = [*(o for f in FORMS for o in _objects(f)), 0, 1, 2, -1, True, False, 0.0, None]


def _call(function: Callable[..., Any], form: Any) -> None:
    # Iterator-returning APIs must reject options at the call, before any iteration.
    if function is dash_table:
        dash_table(form=form)
    elif function is iter_fold_dashes:
        iter_fold_dashes(["x\u2014"], form=form)
    else:
        function("x\u2014", form=form)


def test_the_cases_cover_every_separator_and_space() -> None:
    required = "\t\n\v\f\r\x1c\x1d\x1e\x1f \x85\xa0\u1680\u2000\u200a\u2028\u2029\u3000"
    assert set(required) <= set(SPACES) <= set(DROPPABLE)
    assert {"\u200b", "\u200d", "\u2060", "\ufeff", "\xad", "\x00", "\x7f"} <= set(DROPPABLE)
    for form in FORMS:
        for pad in "\n\r":
            assert {pad + form, form + pad, pad * 2 + form, form + "\r\n"} & set(STR_CASES)
        assert {"\r\n" + form, form + "\r\n", form + "\v", "\f" + form} <= set(STR_CASES)
    assert not set(FORMS) & set(STR_CASES)


@pytest.mark.parametrize("function", APIS, ids=lambda f: f.__name__)
def test_every_api_rejects_every_normalized_spelling(function: Callable[..., Any]) -> None:
    accepted = []
    for form in STR_CASES:
        try:
            with pytest.raises(ValueError, match=VALUE_ERROR):
                _call(function, form)
        except BaseException:
            accepted.append(form)
    assert accepted == []


@pytest.mark.parametrize("function", APIS, ids=lambda f: f.__name__)
def test_every_api_rejects_every_non_str_form(function: Callable[..., Any]) -> None:
    accepted = []
    for form in OBJECT_CASES:
        try:
            with pytest.raises(TypeError, match=TYPE_ERROR):
                _call(function, form)
        except BaseException:
            accepted.append(form)
    assert accepted == []


def test_the_cli_rejects_every_normalized_spelling(capsys: pytest.CaptureFixture[str]) -> None:
    accepted = []
    for form in STR_CASES:
        try:
            code: object = main([f"--form={form}", "--check", "-"])
        except SystemExit as raised:
            code = raised.code
        captured = capsys.readouterr()
        if code != 2 or captured.out or VALUE_ERROR[1:-1] not in captured.err:
            accepted.append(form)
    assert accepted == []
